// The ladder badges as the art set (research/rewards/art/v2/items-v5.json) names them: which mission each
// badge belongs to, its family, tier and finish. The rewards service's missions carry none of this (a tier
// is a "series" mission with a title and a target; its badge is only linked once an admin sets reward_item),
// so the page reads family, tier order, finish and the badge from here, and uses the mission's own
// reward_item instead of the badge when the service has one.

