// T translates a key in the given language, falling back to English and
// finally to the key itself (so missing strings are visible, not blank).
func T(lang, key string) string {
	if c, ok := languages[lang]; ok {
		if s, ok := c[key]; ok {
			return s
		}
	}
	if s, ok := languages["en"][key]; ok {
		return s
	}
	return key
}

// Date writes a day in the language's long form, e.g. "2 January 2006" or
// "2. Januar 2006", from its date.pattern and date.months.
func Date(lang string, t time.Time) string {
	months := strings.Fields(T(lang, "date.months"))
	if len(months) != 12 {
		return t.Format("2006-01-02")
	}
	return strings.NewReplacer("{d}", strconv.Itoa(t.Day()), "{m}", months[t.Month()-1],
		"{y}", strconv.Itoa(t.Year())).Replace(T(lang, "date.pattern"))
}

// CookieName holds a language chosen on the footer form; it beats
// Accept-Language.
const CookieName = "lang"

// Supported lists the languages with a catalogue, English first.
func Supported() []string {
	out := []string{"en"}
	for l := range languages {
		if l != "en" {
			out = append(out, l)
		}
	}
	sort.Strings(out[1:])
	return out
}

// Match returns the catalogue for a language tag: an exact match
// (case-insensitive) or the one sharing its primary subtag, so de-AT reads
// de and pt or pt-PT read pt-BR. "" when none.
func Match(tag string) string {
	tag = strings.ToLower(strings.TrimSpace(tag))
	base, _, _ := strings.Cut(tag, "-")
	for l := range languages {
		if strings.ToLower(l) == tag {
			return l
		}
	}
	for l := range languages {
		if b, _, _ := strings.Cut(strings.ToLower(l), "-"); b == base && base != "" {
			return l
		}
	}
	return ""
}

// Lang resolves the UI language from an Accept-Language header, honouring
// q-values; English when nothing matches.
func Lang(acceptLanguage string) string {
	type pref struct {
		tag string
		q   float64
	}
	var prefs []pref
	for _, part := range strings.Split(acceptLanguage, ",") {
		tag, params, _ := strings.Cut(part, ";")
		q := 1.0
		if v, ok := strings.CutPrefix(strings.TrimSpace(params), "q="); ok {
			if f, err := strconv.ParseFloat(v, 64); err == nil {
				q = f
			}
		}
		if q > 0 {
			prefs = append(prefs, pref{tag, q})
		}
	}
	sort.SliceStable(prefs, func(i, j int) bool { return prefs[i].q > prefs[j].q })
	for _, p := range prefs {
		if l := Match(p.tag); l != "" {
			return l
		}
	}
	return "en"
}

// FromRequest is the language for a request: the lang cookie, else
// Accept-Language.
func FromRequest(r *http.Request) string {
	if c, err := r.Cookie(CookieName); err == nil {
		if l := Match(c.Value); l != "" {
			return l
		}
	}
	return Lang(r.Header.Get("Accept-Language"))
}
