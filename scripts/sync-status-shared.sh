#!/bin/sh
# One visual language for both status pages: the status repository (platforms/core/infra/status)
# owns shared/statusview.css and shared/icons.html; this copies them here. The website builds
# alone in CI, so it cannot import that repository. A test fails when the copies drift.
set -eu
src="${1:-../status/shared}"
root="$(cd "$(dirname "$0")/.." && pwd)"
cp "$src/statusview.css" "$root/web/static/statusview.css"
{
  echo '{{/* GENERATED by scripts/sync-status-shared.sh from the status repository shared/icons.html; do not edit here. */}}'
  echo '{{define "svIcons"}}'
  cat "$src/icons.html"
  echo '{{end}}'
} > "$root/internal/pages/templates/_statusicons.html"
